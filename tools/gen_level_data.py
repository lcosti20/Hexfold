"""Generate src/level/data.rs from the JSON dumps of the Unreal L_Observatory level.

The dumps in tools/unreal_dump/ were taken from the running Unreal editor (Unreal MCP). All
numbers stay in Unreal units (cm, degrees, Unreal axes); src/level/ converts them to Bevy.
Run:  python tools/gen_level_data.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, "unreal_dump")
lv = json.load(open(os.path.join(D, "level.json")))
l2 = json.load(open(os.path.join(D, "level2.json")))
l3 = json.load(open(os.path.join(D, "level3.json")))


def cls(o):
    c = o["class"]
    c = c.get("refPath", "") if isinstance(c, dict) else str(c)
    return c.split(".")[-1].rstrip("'}")


def space(o):
    for t in o["tags"] or []:
        if t.startswith("PortalSpace."):
            return int(t.split(".")[1])
    return -1


def meshname(label):
    v = l3.get(label, {})
    s = v.get("StaticMesh")
    s = s.get("refPath", "") if isinstance(s, dict) else str(s or "")
    return s.split("/")[-1].split(".")[0].strip('"')


out = []
out.append("//! Generated by tools/gen_level_data.py from the Unreal L_Observatory level. Do not edit by hand.\n")
out.append("//! Units are Unreal's: centimetres, degrees (pitch, yaw, roll), Unreal axes. A `space` of -1\n//! means the actor had no `PortalSpace` tag (it appears in every space). `src/level/` converts\n//! everything to Bevy with `crate::ue`.\n")
out.append("#![allow(clippy::all, dead_code)] // the dump keeps every field, used or not\n")
# Keep numbers out of square brackets in these comments: floatify() below rewrites them.
out.append("/// A static mesh actor: a glTF model by name (`SM_...`), or the engine's `Cube` / `Sphere`.")
out.append("pub struct Placed { pub name: &'static str, pub mesh: &'static str, pub loc: [f32; 3], pub rot: [f32; 3], pub scale: [f32; 3], pub space: i32 }")
out.append("/// A portal and the names of the portals its front and back lead to (empty: unlinked).")
out.append("pub struct PortalDef { pub name: &'static str, pub loc: [f32; 3], pub rot: [f32; 3], pub scale: [f32; 3], pub space: i32, pub front: &'static str, pub back: &'static str }")
out.append("/// A point light: intensity in lumens, attenuation radius in cm.")
out.append("pub struct LightDef { pub name: &'static str, pub loc: [f32; 3], pub lumens: f32, pub radius: f32, pub space: i32 }")
out.append("/// A kill volume (`BP_KillVolume`) and where it puts the player back.")
out.append("pub struct KillDef { pub name: &'static str, pub loc: [f32; 3], pub scale: [f32; 3], pub respawn: [f32; 3], pub respawn_yaw: f32, pub space: i32 }")
out.append("/// A rune (`BP_Rune`) where it starts: its index (which hex socket it belongs to) and its scale\n/// (a negative X scale means it starts mirrored).")
out.append("pub struct RuneDef { pub name: &'static str, pub index: u8, pub loc: [f32; 3], pub rot: [f32; 3], pub scale: [f32; 3], pub space: i32 }")
out.append("/// A text render actor: its text and letter height in cm.")
out.append("pub struct TextDef { pub text: &'static str, pub loc: [f32; 3], pub rot: [f32; 3], pub size: f32, pub space: i32 }\n")

# The Unreal level has the Observatory's floor (z = 0) 20 cm above the top of the Ground cube
# (z = -20), so the door stood on a step. The exterior, its doorframe and the entrance portal are
# lowered by that much (cm). The interior (Rotunda, Portal_Entrance_In) keeps its heights: portals
# map heights relative to themselves, so the player still arrives on the Rotunda floor.
LOWER = {"Obs_Exterior": 20, "Obs_DoorframeOut": 20, "Portal_Entrance_Out": 20}


def xf(o):
    """The actor's transform as Rust fields: loc, rot (pitch, yaw, roll), scale."""
    x = o["xf"]; l, r, s = dict(x["location"]), x["rotation"], x["scale"]
    l["z"] -= LOWER.get(o["label"], 0)
    g = lambda v: "%g" % (0 if abs(v) < 1e-6 else round(v, 4))
    return "loc: [%s, %s, %s], rot: [%s, %s, %s], scale: [%s, %s, %s]" % (g(l["x"]), g(l["y"]), g(l["z"]), g(r["pitch"]), g(r["yaw"]), g(r["roll"]), g(s["x"]), g(s["y"]), g(s["z"]))


def emit(name, ty, doc, items):
    out.append("/// %s" % doc)
    out.append("pub const %s: &[%s] = &[" % (name, ty))
    out.extend(items)
    out.append("];\n")


statics, portals, kills, runes, texts = [], [], [], [], []
for o in lv:
    c, lab = cls(o), o["label"]
    if not o["xf"]:
        continue
    if c == "StaticMeshActor":
        statics.append('    Placed { name: "%s", mesh: "%s", %s, space: %d },' % (lab, meshname(lab), xf(o), space(o)))
    elif c == "Portal":
        d = l2[lab]
        portals.append('    PortalDef { name: "%s", %s, space: %d, front: "%s", back: "%s" },' % (lab, xf(o), space(o), d.get("FrontLink") or "", d.get("BackLink") or ""))
    elif c == "BP_KillVolume_C":
        d = l3[lab]["RespawnTransform"]
        l, s = o["xf"]["location"], o["xf"]["scale"]
        rl = d["location"]
        kills.append('    KillDef { name: "%s", loc: [%g, %g, %g], scale: [%g, %g, %g], respawn: [%g, %g, %g], respawn_yaw: %g, space: -1 },' % (lab, l["x"], l["y"], l["z"], s["x"], s["y"], s["z"], rl["x"], rl["y"], rl["z"], d["rotation"]["yaw"]))
    elif c == "BP_Rune_C":
        runes.append('    RuneDef { name: "%s", index: %d, %s, space: %d },' % (lab, l3[lab]["RuneIndex"], xf(o), space(o)))
    elif c == "TextRenderActor":
        v = l3[lab]
        l, r = o["xf"]["location"], o["xf"]["rotation"]
        texts.append('    TextDef { text: "%s", loc: [%g, %g, %g], rot: [%g, %g, %g], size: %g, space: %d },' % (v["Text"], l["x"], l["y"], l["z"], r["pitch"], r["yaw"], r["roll"], v["WorldSize"], space(o)))

# Lights: take the space from the nearest tagged room (by x position), -1 = global.
def light_space(x):
    if abs(x) < 20000: return 0
    return {50000: 1, 80000: 2, 110000: 3, 140000: 4, 170000: 5, 200000: 6, 230000: 7, 260000: 8, 290000: 9}.get(round(x / 10000) * 10000, -1)
lights = []
for o in lv:
    if cls(o) == "PointLight":
        d = l2[o["label"]]; l = o["xf"]["location"]
        lights.append('    LightDef { name: "%s", loc: [%g, %g, %g], lumens: %g, radius: %g, space: %d },' % (o["label"], l["x"], l["y"], l["z"], d["Intensity"], d["AttenuationRadius"], light_space(l["x"])))

emit("STATICS", "Placed", "Every static mesh actor: room shells, doorframes, pedestals, props.", statics)
emit("PORTALS", "PortalDef", "Every portal, with its links by name.", portals)
emit("LIGHTS", "LightDef", "Every point light, with the space of the room it is in.", lights)
emit("KILL_VOLUMES", "KillDef", "The kill volumes under each space and over the chasm pit.", kills)
emit("RUNES", "RuneDef", "The six runes at their starting places.", runes)
emit("TEXTS", "TextDef", "Text in the world (the mural numerals, the mirror gallery inscription).", texts)
text = "\n".join(out)


def floatify(m):
    # Rust needs 1.0, not 1, in f32 arrays.
    return re.sub(r"(?<![\w.])(-?\d+)(?![\w.])", r"\1.0", m.group(0))


text = re.sub(r"(?<!&)\[[^\]\n]*\]", floatify, text)
text = re.sub(r"\b(lumens|radius|size|respawn_yaw): (-?\d+)(?=[,\s])", r"\1: \2.0", text)
# the struct declarations contain "[f32; 3]": undo the damage floatify did to them
text = text.replace("[f32; 3.0]", "[f32; 3]")
open(os.path.join(HERE, "..", "src", "level", "data.rs"), "w", encoding="utf-8").write(text)
print(len(statics), len(portals), len(lights), len(kills), len(runes), len(texts))
